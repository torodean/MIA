#!/usr/bin/env python3
"""
@file    testUI.py
@author  Antonius Torode
@date    09/13/2026

Python UI used by the C++ backend for testing C++/Python communication.

The UI provides two buttons (+1 and -1) and displays a value supplied by the
C++ backend. Button presses are stored as events which can be retrieved by
the C++ backend.

The Python UI does not own or modify the displayed value. The C++ backend is
responsible for maintaining the value and calls setValue() when the displayed
value needs to be updated.
"""

import tkinter as tk


#########################
# CONFIGURATION VARIABLES
#########################

# Enables verbose output.
verboseMode = False


##########
# UI STATE
##########

# Events generated by user interaction with the UI.
# Events remain here until retrieved by the C++ backend.
uiEvents = []


#########################
# INTERNAL HELPER METHODS
#########################

def addEvent(event):
    """
    Adds an event to the UI event queue.

    @param event The event to add to the queue.
    """
    uiEvents.append(event)

    if verboseMode:
        print(f"UI event added: '{event}'")


#####################
# UI EVENT HANDLERS
#####################

def increment():
    """
    Handles the +1 button being clicked.

    The C++ backend is responsible for changing the value. This only reports
    the button click to the C++ backend.
    """
    addEvent("button:+1")


def decrement():
    """
    Handles the -1 button being clicked.

    The C++ backend is responsible for changing the value. This only reports
    the button click to the C++ backend.
    """
    addEvent("button:-1")


###############
# C++ INTERFACE
###############

def setValue(newValue):
    """
    Sets the value displayed by the UI.

    The value is owned and maintained by the C++ backend. This method only
    updates its representation in the Python UI.

    @param newValue The value supplied by the C++ backend.
    """
    valueLabel.config(text=str(newValue))

    if verboseMode:
        print(f"UI value updated to {newValue}")


def getNextEvent():
    """
    Gets the next event generated by the UI.

    Events are removed from the queue when retrieved. An empty string is
    returned when there are no pending events.

    @return The next UI event, or an empty string when the queue is empty.
    """
    if not uiEvents:
        return ""

    return uiEvents.pop(0)


def getAllEvents():
    """
    Gets all events currently generated by the UI.

    Events are removed from the queue when retrieved. An empty list is
    returned when there are no pending events.

    @return A list containing all pending UI events.
    """
    events = uiEvents.copy()
    uiEvents.clear()

    if verboseMode:
        print(f"UI events retrieved: {events}")

    return events


def setVerbose(val):
    """
    Sets whether verbose output is enabled.

    @param val True to enable verbose output, false to disable it.
    """
    global verboseMode
    verboseMode = val

    if verboseMode:
        print("Verbose mode enabled for testUI (python module).")


###############
# CREATE THE UI
###############

root = None
valueLabel = None

def createUI():
    """
    Creates the UI.
    """
    global root
    global valueLabel

    root = tk.Tk()
    root.title("Test UI")

    valueLabel = tk.Label(
        root,
        text="0",
        font=("Arial", 32)
    )
    valueLabel.pack(pady=20)

    buttonFrame = tk.Frame(root)
    buttonFrame.pack(pady=10)

    minusButton = tk.Button(
        buttonFrame,
        text="-1",
        width=10,
        command=decrement
    )
    minusButton.pack(side=tk.LEFT, padx=5)

    plusButton = tk.Button(
        buttonFrame,
        text="+1",
        width=10,
        command=increment
    )
    plusButton.pack(side=tk.LEFT, padx=5)
    
    root.mainloop()


if __name__ == "__main__":
    createUI()
