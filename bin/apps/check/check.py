#!/usr/bin/env python3
"""
@file    checkUI.py
@author  Antonius Torode
@date    10/15/2026

Python UI for the Custom House-made Engine for Chess Knowledge (CHECK)
board.
Used by the C++ backend through PythonModule.

The UI renders an N x M board of square cells with labeled borders and
supports
dragging pieces between squares. All game logic lives in the C++ backend:
the UI never decides whether a move is legal. When a piece is dropped the UI
snaps it back to its origin square and queues a drop_piece event; the backend then
calls movePiece() to make the move official.

Event formats (the C++ side parses these):
   Events (space-separated values, squares are 0-indexed col row):
    "pickup_piece <col> <row>"
    "drop_piece <fromCol> <fromRow> <toCol> <toRow>"
    "reset_board"
    "stop"
   Board state (one string per occupied cell, comma-separated):
    "<col>,<row>,<type>,<color>"
   Position methods accept and return lists of state strings. An empty list
   is an empty board.

The polling listener calls getAllEvents() repeatedly. getAllEvents() pumps
the tkinter event loop before returning, so the UI stays responsive as long
as the backend keeps polling. updateUI() can also be called explicitly.

Square coordinates use a cartesian layout with the origin at the
bottom-left
square. Columns (x) increase left to right and rows (y) increase bottom to
top, so (0, 0) is the bottom-left square. This applies to event strings,
board state strings, and every public method taking a col/row pair.
"""
import tkinter as tk

#########################
# CONFIGURATION VARIABLES
#########################

# Enables verbose output.
verboseMode = False

# Pixel size of one square cell and of the labeled border.
CELL = 90
MARGIN = 34

# Square and label colors.
LIGHT = "#bfa08e"
DARK = "#7d6455"
SELECTED_HIGHLIGHT = "#F7EC59"
LEGAL_MOVE_HIGHLIGHT = "#3db2d3"
LABEL_FG = "#333333"
BACKGROUND = "#ffddc9"

##########
# UI STATE
##########

# Events generated by user interaction with the UI.
# Events remain here until retrieved by the C++ backend.
uiEvents = []

# Registered piece types mapped to their glyphs. 
# These need added using the registerPiece() method.
glyphs = { }

# The root window and the board widget. Both are None until createUI().
root = None
boardUI = None

# The window which displays the game result, or None when no result is
# being displayed. Created by showGameResult().
resultDialog = None


#########################
# INTERNAL HELPER METHODS
#########################

def addEvent(event):
    """
    Adds an event to the UI event queue.
    @param event The event to add to the queue.
    """
    uiEvents.append(event)
    
    # This can be added if desired for debugging, but is generally extremely 
    # noisy, since this method is called frequently.
    #if verboseMode:
    #    print(f"UI event added: '{event}'")


class ChessBoard(tk.Frame):
    """
    The N x M board widget. Pure presentation: it draws squares, labels,
    highlights, and pieces, and converts mouse interaction into string
    events via the module-level addEvent().
    """

    def __init__(self, master, cols, rows):
        super().__init__(master)
        self.rows = rows
        self.cols = cols
        self.board = [[None] * rows for _ in range(cols)]
        self.pieceItems = [[None] * rows for _ in range(cols)]
        self.highlightItems = []
        self.drag = None
        width = cols * CELL + 2 * MARGIN
        height = rows * CELL + 2 * MARGIN
        self.canvas = tk.Canvas(self, width=width, height=height, highlightthickness=0, bg=BACKGROUND)
        self.canvas.pack()
        self.canvas.bind("<Button-1>", self.onPress)
        self.canvas.bind("<B1-Motion>", self.onDrag)
        self.canvas.bind("<ButtonRelease-1>", self.onRelease)
        self.drawBoard()
        self.drawBorderLabels()
        self.pack()

    # ----- drawing -----

    def drawBoard(self):
        """
        Draws the N x M grid of square cells.
        """
        if (verboseMode):
            print("Drawing Board!")

        for col in range(self.cols):
            for row in range(self.rows):
                color = LIGHT if (col + row) % 2 == 0 else DARK
                x0, y0 = self.topLeftPixel(col, row)
                self.canvas.create_rectangle(x0, y0, x0 + CELL, y0 + CELL, fill=color, outline="")

    def drawBorderLabels(self):
        """
        Draws the labeled border: files (a, b, c, ...) below the columns
        and ranks (1, 2, 3, ...) to the left, counting up from the bottom.
        """
        if (verboseMode):
            print("Drawing border labels on board!")

        font = ("Segoe UI", int(CELL * 0.18))
        for row in range(self.rows):
            x = MARGIN - MARGIN // 2
            y = MARGIN + row * CELL + CELL // 2
            self.canvas.create_text(x, y, text=str(self.rows - row), fill=LABEL_FG, font=font)
        for col in range(self.cols):
            x = MARGIN + col * CELL + CELL // 2
            y = MARGIN + self.rows * CELL + MARGIN // 2
            self.canvas.create_text(x, y, text=chr(ord("a") + col), fill=LABEL_FG, font=font)

    def drawPieces(self):
        """
        Redraws every piece from the board data.
        """
        if (verboseMode):
            print("Drawing pieces on board!")

        for col in range(self.cols):
            for row in range(self.rows):
                if self.pieceItems[col][row] is not None:
                    self.canvas.delete(self.pieceItems[col][row])
                    self.pieceItems[col][row] = None
        for col in range(self.cols):
            for row in range(self.rows):
                piece = self.board[col][row]
                if piece is not None:
                    self.pieceItems[col][row] = self.drawPiece(col, row, piece)

    def drawPiece(self, col, row, piece):
        """
        Draws one piece glyph at the center of a square.
        """
        x, y = self.topLeftPixel(col, row)
        return self.canvas.create_text(
            x + CELL // 2, y + CELL // 2, text=glyphs[piece["type"]],
            font=("Segoe UI Symbol", int(CELL * 0.6)),
            fill="white" if piece["color"] == "white" else "black",
        )

    # ----- geometry -----

    def topLeftPixel(self, col, row):
        """
        Top-left pixel of a square. Row 0 is the bottom row.
        """
        return (MARGIN + col * CELL, MARGIN + (self.rows - 1 - row) * CELL)

    def squareAt(self, x, y):
        """
        Converts pixel coordinates to a (col, row) square. Row 0 is the bottom row.
        @return The (col, row) tuple, or None when off the board.
        """
        x -= MARGIN
        y -= MARGIN
        if not (0 <= x < CELL * self.cols and 0 <= y < CELL * self.rows):
            return None
        return (int(x // CELL), int(self.rows - 1 - y // CELL))

    # ----- mouse handling -----

    def onPress(self, event):
        """
        Begins a drag when a square holding a piece is pressed.
        The piece glyph is removed from its square so it appears lifted,
        and only the glyph following the mouse remains visible.
        """
        sq = self.squareAt(event.x, event.y)
        if sq is None or self.board[sq[0]][sq[1]] is None:
            return
        col, row = sq
        highlightSquare(col, row, SELECTED_HIGHLIGHT)
        self.drag = {"from": sq}
        addEvent(f"pickup_piece {col} {row}")
        # Hide the piece on its square so it is not duplicated during
        # the drag; drawPieces() restores it if the drop is invalid.
        self.canvas.delete(self.pieceItems[col][row])
        self.pieceItems[col][row] = None
        self.drag["item"] = self.drawPiece(col, row, self.board[col][row])
        self.canvas.tag_raise(self.drag["item"])

    def onDrag(self, event):
        """
        Moves the dragged piece glyph with the mouse.
        """
        if self.drag is None:
            return
        self.canvas.coords(self.drag["item"], event.x, event.y)

    def onRelease(self, event):
        """
        Ends a drag. The piece snaps back to its origin; the backend
        confirms the move by calling movePiece().
        """
        clearHighlights()
        if self.drag is None:
            return
        src = self.drag["from"]
        self.canvas.delete(self.drag["item"])
        self.drag = None
        dst = self.squareAt(event.x, event.y)
        self.drawPieces()
        if dst is not None and dst != src:
            addEvent(f"drop_piece {src[0]} {src[1]} {dst[0]} {dst[1]}")


#####################
# UI EVENT HANDLERS
#####################

def closeUI():
    addEvent("stop")
    root.destroy()


#####################
# INTERNAL BOARD OPS
#####################

def validateCell(col, row, pieceType=None):
    """
    Raises ValueError for an out-of-range square or unregistered type.
    @param col The column.
    @param row The row.
    @param pieceType The piece type name, or None to skip the type check.
    """
    if boardUI is None:
        raise ValueError("UI not created; call createUI() first.")
    if not (0 <= col < boardUI.cols and 0 <= row < boardUI.rows):
        raise ValueError(f"Square ({col}, {row}) out of range.")
    if pieceType is not None and pieceType not in glyphs:
        raise ValueError(f"Unregistered piece type: '{pieceType}'")


###############
# C++ INTERFACE
###############

def createUI(cols, rows):
    """
    Creates the UI with an empty cols x rows board.
    @param cols The number of columns (m).
    @param rows The number of rows (n).
    """
    if (verboseMode):
        print(f"Creating UI board of size ({cols},{rows})!")

    global root, boardUI, uiEvents, resultDialog
    if root is not None:
        # The result window is a child of the root window, so it is destroyed
        # with it and the stale reference has to be dropped.
        root.destroy()
        resultDialog = None
    root = tk.Tk()
    root.title("CHECK: Custom House-made Engine for Chess Knowledge")
    boardUI = ChessBoard(root, cols, rows)
    uiEvents = []
    # Handles when the window is deleted.
    root.protocol("WM_DELETE_WINDOW", closeUI)


def registerPiece(name, icon):
    """
    Registers a custom piece type by name and icon glyph.
    The backend owns all rules for the type; this only makes it drawable.
    @param name The piece type name used in setBoardState()/movePiece().
    @param icon The unicode character (or any string) used as the icon.
    """
    if (verboseMode):
        print(f"Adding {name} piece with icon {icon} to glyphs!")
    glyphs[name] = icon


def setBoardState(cells):
    """
    Replaces the whole board state from a list of state strings.
    @param cells A list of "<col>,<row>,<type>,<color>" strings. An empty
        list clears the board. Cells not listed become empty.
    """
    if (verboseMode):
        print(f"Setting board state using input of:\n{cells}\n")

    if boardUI is None:
        raise ValueError("UI not created; call createUI() first")

    boardUI.board = [[None] * boardUI.rows for _ in range(boardUI.cols)]
    for cell in cells:
        col, row, pieceType, color = cell.split(",")
        validateCell(int(col), int(row), pieceType)
        boardUI.board[int(col)][int(row)] = {"type": pieceType, "color": color}

    boardUI.drawPieces()


def getBoardState():
    """
    Returns the current board state as state strings.
    @return A list of "<col>,<row>,<type>,<color>" strings for occupied cells.
    """
    if boardUI is None:
        return []
    cells = []
    for col in range(boardUI.cols):
        for row in range(boardUI.rows):
            piece = boardUI.board[col][row]
            if piece is not None:
                cells.append(f"{col},{row},{piece['type']},{piece['color']}")

    return cells


def movePiece(fromCol, fromRow, toCol, toRow):
    """
    Moves a piece in the board data and redraws.
    Called by the backend after a drop_piece event is judged legal.
    @param fromCol The source column.
    @param fromRow The source row.
    @param toCol The destination column.
    @param toRow The destination row.
    """
    # Make sure the inputs are valid.
    validateCell(fromCol, fromRow)
    validateCell(toCol, toRow)
    if boardUI.board[fromCol][fromRow] is None:
        raise ValueError(f"No piece on source square: ({fromCol},{fromRow})")

    boardUI.board[toCol][toRow] = boardUI.board[fromCol][fromRow]
    boardUI.board[fromCol][fromRow] = None
    boardUI.drawPieces()


def removePiece(col, row):
    """
    Removes a piece from the board data and redraws.
    @param col The column of the square.
    @param row The row of the square.
    """
    # Make sure the inputs are valid.
    validateCell(col, row)

    boardUI.board[col][row] = None
    boardUI.drawPieces()


def highlightSquare(col, row, color=LEGAL_MOVE_HIGHLIGHT):
    """
    Draws a highlight outline on one square.
    @param col The column of the square.
    @param row The row of the square.
    @param color Optional outline color.
    """
    if boardUI is None:
        return
    x0, y0 = boardUI.topLeftPixel(col, row)
    item = boardUI.canvas.create_rectangle(
        x0 + 3, y0 + 3, x0 + CELL - 3, y0 + CELL - 3,
        outline=color, width=4,
    )
    boardUI.highlightItems.append(item)
    updateUI()


def clearHighlights():
    """
    Removes all square highlights.
    """
    if boardUI is None:
        return
    for item in boardUI.highlightItems:
        boardUI.canvas.delete(item)
    boardUI.highlightItems = []
    updateUI()


def resetBoard():
    """
    Closes the game result window and queues a reset_board event.
    The backend answers the event by starting a new game and sending the
    starting board state back to the UI with setBoardState().
    """
    global resultDialog
    if (verboseMode):
        print("Resetting board!")

    if resultDialog is not None:
        resultDialog.grab_release()
        resultDialog.destroy()
        resultDialog = None

    addEvent("reset_board")


def showGameResult(result, reason, winner="none"):
    """
    Displays the result of a finished game with a single reset option.
    The backend ignores pickup and drop events once the game is over, so the
    window cannot be dismissed without resetting; closing it resets too.
    @param result The result of the game: "win" or "draw".
    @param reason Why the game ended, e.g. "checkmate", "stalemate" or
        "insufficient material".
    @param winner The color of the winner, or "none" for a draw.
    """
    if (verboseMode):
        print(f"Showing game result: {result} ({reason}), winner: {winner}")

    if root is None:
        raise ValueError("UI not created; call createUI() first")

    global resultDialog

    if result == "win":
        message = f"{winner.capitalize()} wins by {reason}."
    else:
        message = f"Draw by {reason}."

    if resultDialog is not None:
        resultDialog.destroy()

    resultDialog = tk.Toplevel(root)
    resultDialog.title("Game Over")
    resultDialog.resizable(False, False)
    resultDialog.transient(root)
    tk.Label(resultDialog, text=message, font=("Segoe UI", 14),
             bg=BACKGROUND, fg=LABEL_FG).pack(padx=24, pady=(18, 12))
    tk.Button(resultDialog, text="Reset", command=resetBoard).pack(padx=24,
                                                                  pady=(0, 18))
    resultDialog.protocol("WM_DELETE_WINDOW", resetBoard)
    resultDialog.wait_visibility(resultDialog)
    resultDialog.grab_set()
    updateUI()


def updateUI():
    """
    Processes pending tkinter events and redraws the window.
    The backend can call this to keep the UI responsive between polls.
    """
    if root is not None:
        root.update()


def getNextEvent():
    """
    Gets the next event generated by the UI.
    Events are removed from the queue when retrieved. An empty string is
    returned when there are no pending events.
    @return The next UI event, or an empty string when the queue is empty.
    """
    if not uiEvents:
        return ""
    return uiEvents.pop(0)


def getAllEvents():
    """
    Gets all events currently generated by the UI.
    Events are removed from the queue when retrieved. An empty list is
    returned when there are no pending events.
    The tkinter event loop is pumped on each call so that mouse-driven
    events keep flowing without a separate mainloop on the python side.
    @return A list containing all pending UI events.
    """
    events = uiEvents.copy()
    uiEvents.clear()

    # This can be added if desired for debugging, but is generally extremely 
    # noisy, since this method is called frequently.
    #if verboseMode:
    #    print(f"UI events retrieved: {events}")

    return events


def setVerbose(val):
    """
    Sets whether verbose output is enabled.
    @param val True to enable verbose output, false to disable it.
    """
    global verboseMode
    verboseMode = val
    if verboseMode:
        print("Verbose mode enabled for chessUI (python module).")


def main():
    """
    Standalone 5x6 sample for testing the UI without the C++ backend.
    """
    setVerbose(True)
    createUI(5, 6)
    registerPiece("king", "\u265A")
    registerPiece("queen", "\u265B")
    registerPiece("pawn", "\u265F")
    registerPiece("knight", "\u265E")
    setBoardState([
        # Add kings.
        "0,0,king,white",
        "4,5,king,black",

        # Add queens.
        "4,0,queen,white",
        "0,5,queen,black",

        # Add pawns.
        "0,1,pawn,white",
        "1,1,pawn,white",
        "2,1,pawn,white",
        "3,1,pawn,white",
        "4,1,pawn,white",
        "0,4,pawn,black",
        "1,4,pawn,black",
        "2,4,pawn,black",
        "3,4,pawn,black",
        "4,4,pawn,black",

        # Add knights.
        "2,0,knight,white",
        "2,5,knight,black",
    ])
    root.mainloop()


if __name__ == "__main__":
    main()
