def main():
    """
    Standalone 5x6 sample for testing the UI without the C++ backend. This only
    handles visuals and picking up pieces, it does not handle moving pieces since
    that is all handled by the C++ backend.
    """
    setVerbose(True)
    createUI(5, 6)
    registerPiece("king", "\u265A")
    registerPiece("queen", "\u265B")
    registerPiece("pawn", "\u265F")
    registerPiece("knight", "\u265E")
    registerPiece("templar", "\u2720")
    setBoardState([
        # Add kings.
        "0,0,king,white",
        "4,5,king,black",
        # Add queens.
        "4,0,queen,white",
        "0,5,queen,black",

        # Add pawns.
        "0,1,pawn,white",
        "1,2,pawn,white",
        "2,2,pawn,white",
        "3,1,pawn,white",
        "4,1,pawn,white",
        "0,4,pawn,black",
        "1,3,pawn,black",
        "2,4,pawn,black",
        "3,4,pawn,black",
        "4,4,pawn,black",

        # Add knights.
        "2,0,knight,white",
        "2,5,knight,black",

        # Add a custom piece.
        "1,0,templar,white",
        "3,5,templar,black",
    ])

    # Panel content: a short opening, black to move.
    addMoveToHistory("white", "c3")
    addMoveToHistory("black", "b4")
    addMoveToHistory("white", "b3")
    setTurn("black")
    optionsPanel.show()
    root.mainloop()

if __name__ == "__main__":
    main()
