def closeUI():
    """
    Destroys the UI and queues a stop event.
    The backend responds to the event by ending the program.
    """
    addEvent("stop")
    root.destroy()

def resetBoard():
    """
    Closes the game result window and queues a reset_board event.
    The backend answers the event by starting a new game and sending the
    starting board state back to the UI with setBoardState().
    """
    global resultDialog
    if (verboseMode):
        pythonTools.output_text("Resetting board!", option="note")

    if resultDialog is not None:
        resultDialog.destroy()
        resultDialog = None

    addEvent("reset_board")

def sendPiecePromoChoice(piece):
    """
    Closes the piece promotion window and queues a piece_promo_choice event.
    The backend answers the event by promoting the appropriate piece and 
    updating the board state.
    @param piece The piece promotion choice.
    """
    global piecePromoBox
    if (verboseMode):
        pythonTools.output_text("Promoting piece!", option="note")

    if piecePromoBox is not None:
        piecePromoBox.grab_release()
        piecePromoBox.destroy()
        piecePromoBox = None

    addEvent(f"piece_promo_choice;{piece}")


def saveBoard():
    """
    Prompts the user for a file location and queues a save_board event with the
    chosen path so the backend can write the current board state to it. If the
    user cancels the file dialog, no event is queued.
    """
    saveFile = filedialog.asksaveasfilename(
        title="Save Board State",
        defaultextension=".check",
        filetypes=[("Check save files", "*.check"), ("All files", "*.*")],
    )
    if saveFile:
        if (verboseMode):
            pythonTools.output_text(f"Saving board to: {saveFile}", option="note")
        addEvent(f"save_board;{saveFile}")


def loadBoard():
    """
    Prompts the user for a saved file and queues a load_board event with the
    chosen path so the backend can restore the board state from it. If the
    user cancels the file dialog, no event is queued.
    """
    loadFile = filedialog.askopenfilename(
        title="Load Board State",
        filetypes=[("Check save files", "*.check"), ("All files", "*.*")],
    )
    if loadFile:
        if (verboseMode):
            pythonTools.output_text(f"Loading board from: {loadFile}", option="note")
        addEvent(f"load_board;{loadFile}")


def rotateBoard():
    """
    Rotates the board 180 degrees in place. The position is left identical;
    only the side the board is viewed from changes. This is a pure view change,
    so no board data is altered and no event is queued. It can be triggered from
    the Game menu / Ctrl+R, or called directly by the C++ backend.
    """
    if boardUI is None:
        return
    if (verboseMode):
        pythonTools.output_text("Rotating board!", option="note")
    boardUI.rotate()
    updateUI()


