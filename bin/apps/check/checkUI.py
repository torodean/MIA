class ChessBoard(tk.Frame):
    """
    The N x M board widget. Pure presentation: it draws squares, labels,
    highlights, and pieces, and converts mouse interaction into string
    events via the module-level addEvent().
    """

    def __init__(self, master, cols, rows):
        super().__init__(master)
        self.rows = rows
        self.cols = cols
        self.board = [[None] * rows for _ in range(cols)]
        self.pieceItems = [[None] * rows for _ in range(cols)]
        self.highlightItems = []
        self.arrows = []
        self.arrow = None
        self.squareHighlights = []
        self.drag = None
        # True once the board has been rotated 180 degrees, so the geometry
        # methods can mirror every square across the board's center. The border
        # labels stay in place and only their values change to match.
        self.rotated = False
        # The labeled border only occupies the left and bottom margins. The
        # squares sit flush with the right edge, so the collapse bar sits
        # directly against the board there.
        width = cols * CELL + MARGIN
        height = rows * CELL + 2 * MARGIN
        self.canvas = tk.Canvas(self, width=width, height=height, highlightthickness=0, bg=BACKGROUND)
        self.canvas.pack()
        self.canvas.bind("<Button-1>", self.onPress)
        self.canvas.bind("<B1-Motion>", self.onDrag)
        self.canvas.bind("<ButtonRelease-1>", self.onRelease)
        self.canvas.bind("<Button-3>", self.onRightPress)
        self.canvas.bind("<B3-Motion>", self.onRightDrag)
        self.canvas.bind("<ButtonRelease-3>", self.onRightRelease)
        self.drawBoard()
        self.drawBorderLabels()
        # The board packs on the left of the main row, so the options bar
        # and panel can sit to its right.
        self.pack(side=tk.LEFT)

    # ----- drawing -----

    def drawBoard(self):
        """
        Draws the N x M grid of square cells.
        """
        if (verboseMode):
            pythonTools.output_text("Drawing Board!", option="program")

        for col in range(self.cols):
            for row in range(self.rows):
                color = LIGHT if (col + row) % 2 == 0 else DARK
                x0, y0 = self.topLeftPixel(col, row)
                self.canvas.create_rectangle(x0, y0, x0 + CELL, y0 + CELL, fill=color, outline="")

    def drawBorderLabels(self):
        """
        Draws the labeled border: files (a, b, c, ...) below the columns and
        ranks (1, 2, 3, ...) to the left, counting up from the bottom. The
        labels always sit in these same places; when the board is rotated only
        their values change, so each names the square now shown in its slot.
        """
        if (verboseMode):
            pythonTools.output_text("Drawing border labels on board!", option="program")

        font = ("Segoe UI", int(CELL * 0.18))
        for row in range(self.rows):
            x = MARGIN - MARGIN // 2
            y = MARGIN + row * CELL + CELL // 2
            # The rank of the square now shown in this row of the frame.
            rank = row if self.rotated else (self.rows - 1 - row)
            self.canvas.create_text(x, y, text=str(rank + 1), fill=LABEL_FG, font=font)
        for col in range(self.cols):
            x = MARGIN + col * CELL + CELL // 2
            y = MARGIN + self.rows * CELL + MARGIN // 2
            # The file of the square now shown in this column of the frame.
            fileCol = (self.cols - 1 - col) if self.rotated else col
            self.canvas.create_text(x, y, text=chr(ord("a") + fileCol), fill=LABEL_FG, font=font)

    def drawPieces(self):
        """
        Redraws every piece from the board data.
        """
        if (verboseMode):
            pythonTools.output_text("Drawing pieces on board!", option="program")

        for col in range(self.cols):
            for row in range(self.rows):
                if self.pieceItems[col][row] is not None:
                    self.canvas.delete(self.pieceItems[col][row])
                    self.pieceItems[col][row] = None
        for col in range(self.cols):
            for row in range(self.rows):
                piece = self.board[col][row]
                if piece is not None:
                    self.pieceItems[col][row] = self.drawPiece(col, row, piece)

    def drawPiece(self, col, row, piece):
        """
        Draws one piece glyph at the center of a square.
        """
        x, y = self.topLeftPixel(col, row)
        return self.canvas.create_text(
            x + CELL // 2, y + CELL // 2, text=glyphs[piece["type"]],
            font=("Segoe UI Symbol", int(CELL * 0.6)),
            fill="white" if piece["color"] == "white" else "black",
        )

    # ----- geometry -----

    def screenCoord(self, col, row):
        """
        The (col, row) slot a logical square is drawn in, applying the
        current rotation. Not rotated, this is the square itself. Rotated,
        the board is turned 180 degrees, so the square lands in the
        diagonally opposite slot.
        @param col The logical column.
        @param row The logical row.
        @return The (col, row) slot the square is drawn in.
        """
        if self.rotated:
            return (self.cols - 1 - col, self.rows - 1 - row)
        return (col, row)

    def topLeftPixel(self, col, row):
        """
        Top-left pixel of a square. Row 0 is the bottom row. Accounts for the
        current rotation.
        """
        scol, srow = self.screenCoord(col, row)
        return (MARGIN + scol * CELL, MARGIN + (self.rows - 1 - srow) * CELL)

    def squareCenterPixel(self, col, row):
        """
        Center pixel of a square. Row 0 is the bottom row. Accounts for the
        current rotation.
        """
        x, y = self.topLeftPixel(col, row)
        return (x + CELL // 2, y + CELL // 2)

    def squareAt(self, x, y):
        """
        Converts pixel coordinates to a (col, row) square. Row 0 is the bottom row.
        Accounts for the current rotation.
        @return The (col, row) tuple, or None when off the board.
        """
        x -= MARGIN
        y -= MARGIN
        if not (0 <= x < CELL * self.cols and 0 <= y < CELL * self.rows):
            return None
        scol = int(x // CELL)
        srow = int(self.rows - 1 - y // CELL)
        if self.rotated:
            return (self.cols - 1 - scol, self.rows - 1 - srow)
        return (scol, srow)

    def rotate(self):
        """
        Rotates the board 180 degrees in place. The board data (which piece
        sits on which square) is left untouched, so the position is identical;
        only the side it is viewed from changes. The squares and pieces are
        redrawn at their mirrored slots, and the border labels are redrawn with
        the values of the squares now shown in each slot. The annotations are
        dropped because they were drawn against the old orientation.
        """
        self.rotated = not self.rotated
        self.canvas.delete("all")
        self.highlightItems = []
        self.arrows = []
        self.squareHighlights = []
        self.drag = None
        self.drawBoard()
        self.drawBorderLabels()
        self.drawPieces()

    # ----- annotations -----

    def clearAnnotations(self):
        """
        Removes every annotation from the board: all arrows and all square
        highlights. Called whenever the position changes, since annotations
        drawn against the old position no longer mean anything.
        """
        self.clearArrows()
        self.clearSquareHighlights()

    def clearSquareAnnotations(self, square):
        """
        Removes the annotations which come from one square: the arrows leaving
        it and its highlight, leaving the other squares untouched. Called when
        a square's piece is picked up.
        @param square The (col, row) square the annotations come from.
        """
        self.clearArrowsFrom(square)
        self.clearSquareHighlight(square)

    # ----- annotation arrows -----

    def drawArrow(self, fromSquare, toSquare):
        """
        Draws an annotation arrow between the centers of two squares.
        @param fromSquare The (col, row) square the arrow starts on.
        @param toSquare The (col, row) square the arrow points at.
        @return The canvas item id of the arrow.
        """
        startX, startY = self.squareCenterPixel(*fromSquare)
        endX, endY = self.squareCenterPixel(*toSquare)
        return self.canvas.create_line(startX, startY, endX, endY,
                                      fill=ARROW_COLOR, width=ARROW_WIDTH,
                                      arrow=tk.LAST, arrowshape=ARROW_HEAD,
                                      capstyle=tk.ROUND)

    def findArrow(self, fromSquare, toSquare):
        """
        Finds the arrow already drawn between two squares.
        @param fromSquare The (col, row) square the arrow starts on.
        @param toSquare The (col, row) square the arrow points at.
        @return The arrow record, or None when no such arrow is drawn.
        """
        for arrow in self.arrows:
            if arrow["from"] == fromSquare and arrow["to"] == toSquare:
                return arrow
        return None

    def clearArrows(self):
        """
        Removes every annotation arrow from the board, leaving the square
        highlights untouched.
        """
        for arrow in self.arrows:
            self.canvas.delete(arrow["item"])
        self.arrows = []

    def clearArrowsFrom(self, square):
        """
        Removes the annotation arrows which come from one square, leaving the
        rest of the arrows on the board untouched.
        @param square The (col, row) square the arrows start on.
        @return The number of arrows removed.
        """
        remaining = []
        removed = 0
        for arrow in self.arrows:
            if arrow["from"] == square:
                self.canvas.delete(arrow["item"])
                removed += 1
            else:
                remaining.append(arrow)
        self.arrows = remaining
        return removed

    # ----- square highlights -----

    def findSquareHighlight(self, square):
        """
        Finds the persistent highlight drawn on one square.
        @param square The (col, row) square to look for.
        @return The highlight record, or None when the square is not
        highlighted.
        """
        for highlight in self.squareHighlights:
            if highlight["square"] == square:
                return highlight
        return None

    def toggleSquareHighlight(self, square):
        """
        Highlights a square, or removes the highlight when the square is
        already highlighted. Drawn in the same inset outline style as the
        selection and legal-move highlights.
        @param square The (col, row) square to toggle the highlight on.
        """
        if self.clearSquareHighlight(square):
            return
        x0, y0 = self.topLeftPixel(*square)
        item = self.canvas.create_rectangle(
            x0 + 3, y0 + 3, x0 + CELL - 3, y0 + CELL - 3,
            outline=SQUARE_HIGHLIGHT, width=4,
        )
        self.squareHighlights.append({"item": item, "square": square})

    def clearSquareHighlight(self, square):
        """
        Removes the persistent highlight from one square, if it has one,
        leaving the highlights on the other squares untouched.
        @param square The (col, row) square the highlight is on.
        @return True when a highlight was removed, false when there was none.
        """
        existing = self.findSquareHighlight(square)
        if existing is None:
            return False
        self.canvas.delete(existing["item"])
        self.squareHighlights.remove(existing)
        return True

    def clearSquareHighlights(self):
        """
        Removes every persistent square highlight from the board.
        """
        for highlight in self.squareHighlights:
            self.canvas.delete(highlight["item"])
        self.squareHighlights = []

    # ----- mouse handling -----

    def onPress(self, event):
        """
        Begins a drag when a square holding a piece is pressed.
        The piece glyph is removed from its square so it appears lifted,
        and only the glyph following the mouse remains visible. Picking a piece
        up drops the annotations which come from its square: the arrows leaving
        it and its highlight.
        """
        sq = self.squareAt(event.x, event.y)
        if sq is None or self.board[sq[0]][sq[1]] is None:
            return
        col, row = sq
        # The picked square is about to change, so the annotations which come
        # from it go away: its arrows and its highlight together.
        self.clearSquareAnnotations(sq)
        highlightSquare(col, row, SELECTED_HIGHLIGHT)
        self.drag = {"from": sq}
        addEvent(f"pickup_piece;{col};{row}")
        # Hide the piece on its square so it is not duplicated during
        # the drag; drawPieces() restores it if the drop is invalid.
        self.canvas.delete(self.pieceItems[col][row])
        self.pieceItems[col][row] = None
        self.drag["item"] = self.drawPiece(col, row, self.board[col][row])
        self.canvas.tag_raise(self.drag["item"])

    def onDrag(self, event):
        """
        Moves the dragged piece glyph with the mouse.
        """
        if self.drag is None:
            return
        self.canvas.coords(self.drag["item"], event.x, event.y)

    def onRelease(self, event):
        """
        Ends a drag. The piece snaps back to its origin; the backend
        confirms the move by calling movePiece().
        """
        clearHighlights()
        if self.drag is None:
            return
        src = self.drag["from"]
        self.canvas.delete(self.drag["item"])
        self.drag = None
        dst = self.squareAt(event.x, event.y)
        self.drawPieces()
        if dst is not None and dst != src:
            addEvent(f"drop_piece;{src[0]};{src[1]};{dst[0]};{dst[1]}")

    def onRightPress(self, event):
        """
        Begins a right button gesture on the square the button was pressed on.
        Dragging the gesture to another square draws an annotation arrow, and
        a release on the pressed square itself toggles its highlight. Arrows
        and highlights are a local UI note, they are never queued as backend
        events.
        """
        sq = self.squareAt(event.x, event.y)
        if sq is None:
            return
        self.arrow = {"from": sq, "to": None, "item": None, "dragged": False}

    def onRightDrag(self, event):
        """
        Stretches the annotation arrow to the square under the mouse.
        The arrow is redrawn rather than stretched to the cursor so that it
        always snaps to whole squares instead of ending mid-square.
        """
        if self.arrow is None:
            return
        sq = self.squareAt(event.x, event.y)
        if sq is None or sq == self.arrow["from"]:
            # No square to point at yet, so no arrow should be showing.
            if self.arrow["item"] is not None:
                self.canvas.delete(self.arrow["item"])
                self.arrow["item"] = None
                self.arrow["to"] = None
            return
        if self.arrow["item"] is not None:
            self.canvas.delete(self.arrow["item"])
        self.arrow["item"] = self.drawArrow(self.arrow["from"], sq)
        self.arrow["to"] = sq
        self.arrow["dragged"] = True

    def onRightRelease(self, event):
        """
        Finishes an annotation arrow. A drag onto a different square leaves the
        arrow on the board, unless that exact arrow is already drawn, in which
        case drawing it again removes it. A right click which never left its own
        square toggles a persistent highlight on that square.
        """
        if self.arrow is None:
            return
        arrow = self.arrow
        self.arrow = None

        if arrow["item"] is None:
            if arrow["dragged"]:
                # The drag ended off the board or back on its own square, which
                # cancels it without touching the arrows already drawn.
                updateUI()
                return
            # The button never dragged to another square, so this is a request
            # to toggle a persistent highlight on the pressed square.
            self.toggleSquareHighlight(arrow["from"])
            updateUI()
            return

        existing = self.findArrow(arrow["from"], arrow["to"])
        if existing is not None:
            # This arrow is already drawn, so drawing it again removes it.
            self.canvas.delete(existing["item"])
            self.arrows.remove(existing)
            self.canvas.delete(arrow["item"])
        else:
            self.arrows.append({"item": arrow["item"],
                                "from": arrow["from"],
                                "to": arrow["to"]})
        updateUI()


