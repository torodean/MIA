def createUI(cols, rows):
    """
    Creates the UI with an empty cols x rows board.
    @param cols The number of columns (m).
    @param rows The number of rows (n).
    """
    if (verboseMode):
        pythonTools.output_text(f"Creating UI board of size ({cols},{rows})!", option="program")

    global root, boardUI, uiEvents, resultDialog, piecePromoBox, optionsPanel, menuBar
    if root is not None:
        root.destroy()
        # The additional windows are children of the root window, so they are destroyed
        # with it and the stale references have to be dropped.
        resultDialog = None
        piecePromoBox = None
    root = tk.Tk()
    root.title("CHECK: Custom House-made Engine for Chess Knowledge")

    # ----- The menu bar -----
    menuBar = tk.Menu(root, tearoff=0)

    fileMenu = tk.Menu(menuBar, tearoff=0)
    fileMenu.add_command(label="Save", accelerator="Ctrl+S",
                         command=saveBoard)
    fileMenu.add_command(label="Load", accelerator="Ctrl+L",
                         command=loadBoard)
    fileMenu.add_separator()
    # Exit reuses closeUI(), so it behaves exactly like closing the window.
    fileMenu.add_command(label="Exit", command=closeUI)
    menuBar.add_cascade(label="File", menu=fileMenu)

    gameMenu = tk.Menu(menuBar, tearoff=0)
    # Rotation is a local UI action, so it calls rotateBoard() directly rather
    # than queueing an event for the backend.
    gameMenu.add_command(label="Rotate Board", accelerator="Ctrl+R",
                         command=rotateBoard)
    gameMenu.add_command(label="Undo", accelerator="Ctrl+Z",
                         command=lambda: addEvent("undo_move"))
    # Still being developed.
    #gameMenu.add_command(label="Edit",
    #                     command=lambda: addEvent("edit_mode"))
    menuBar.add_cascade(label="Game", menu=gameMenu)

    root.config(menu=menuBar)

    # The accelerator labels above only display the shortcuts; tkinter
    # needs explicit bindings for the keys to actually fire the events.
    root.bind("<Control-s>", lambda event: saveBoard())
    root.bind("<Control-l>", lambda event: loadBoard())
    root.bind("<Control-z>", lambda event: addEvent("undo_move"))
    root.bind("<Control-r>", lambda event: rotateBoard())

    # The board, the collapse bar and the options panel share one row,
    # packed left to right. The panel can then open beside the board
    # without disturbing it.
    mainRow = tk.Frame(root)
    mainRow.pack()
    boardUI = ChessBoard(mainRow, cols, rows)
    optionsPanel = optionsUI.OptionsPanel(mainRow, addEvent, glyphs)

    uiEvents = []
    # Handles when the window is deleted.
    root.protocol("WM_DELETE_WINDOW", closeUI)

def updateUI():
    """
    Processes pending tkinter events and redraws the window.
    The backend can call this to keep the UI responsive between polls.
    """
    if root is not None:
        root.update()


# ----- board state -----

def registerPiece(name, icon):
    """
    Registers a custom piece type by name and icon glyph.
    The backend owns all rules for the type; this only makes it drawable.
    @param name The piece type name used in setBoardState()/movePiece().
    @param icon The unicode character (or any string) used as the icon.
    """
    if icon.startswith("\\u") and len(icon) == 6:
        icon = chr(int(icon[2:], 16))

    if (verboseMode):
        pythonTools.output_text(f"Adding {name} piece with icon {icon} to glyphs!", option="program")

    glyphs[name] = icon
    if optionsPanel is not None:
        # The panel may already be drawing this piece in the turn indicator.
        optionsPanel.updateGlyphs()

def setBoardState(cells):
    """
    Replaces the whole board state from a list of state strings.
    @param cells A list of "<col>,<row>,<type>,<color>" strings. An empty
        list clears the board. Cells not listed become empty.
    """
    if (verboseMode):
        pythonTools.output_text(f"Setting board state using input of:\n{cells}", option="note")

    if boardUI is None:
        raise ValueError("UI not created; call createUI() first")

    boardUI.board = [[None] * boardUI.rows for _ in range(boardUI.cols)]
    for cell in cells:
        col, row, pieceType, color = cell.split(",")
        validateCell(int(col), int(row), pieceType)
        boardUI.board[int(col)][int(row)] = {"type": pieceType, "color": color}

    # The whole position has been replaced, so any annotations drawn against
    # the old one no longer mean anything.
    boardUI.clearAnnotations()
    boardUI.drawPieces()

def getBoardState():
    """
    Returns the current board state as state strings.
    @return A list of "<col>,<row>,<type>,<color>" strings for occupied cells.
    """
    if boardUI is None:
        return []
    cells = []
    for col in range(boardUI.cols):
        for row in range(boardUI.rows):
            piece = boardUI.board[col][row]
            if piece is not None:
                cells.append(f"{col},{row},{piece['type']},{piece['color']}")

    return cells

def movePiece(fromCol, fromRow, toCol, toRow):
    """
    Moves a piece in the board data and redraws.
    Called by the backend after a drop_piece event is judged legal.
    @param fromCol The source column.
    @param fromRow The source row.
    @param toCol The destination column.
    @param toRow The destination row.
    """
    # Make sure the inputs are valid.
    validateCell(fromCol, fromRow)
    validateCell(toCol, toRow)
    if boardUI.board[fromCol][fromRow] is None:
        raise ValueError(f"No piece on source square: ({fromCol},{fromRow})")

    boardUI.board[toCol][toRow] = boardUI.board[fromCol][fromRow]
    boardUI.board[fromCol][fromRow] = None
    boardUI.clearAnnotations()
    boardUI.drawPieces()

def setPiece(piece, color, col, row):
    """
    Sets a piece from the board data and redraws.
    @param piece The piece to set.
    @param col The column of the square.
    @param row The row of the square.
    """
    # Make sure the inputs are valid.
    validateCell(col, row)

    boardUI.board[col][row] = {"type": piece, "color": color}
    boardUI.clearAnnotations()
    boardUI.drawPieces()

def removePiece(col, row):
    """
    Removes a piece from the board data and redraws.
    @param col The column of the square.
    @param row The row of the square.
    """
    # Make sure the inputs are valid.
    validateCell(col, row)

    boardUI.board[col][row] = None
    boardUI.clearAnnotations()
    boardUI.drawPieces()


# ----- dialogs -----

def showGameResult(result, reason, winner="none"):
    """
    Displays the result of a finished game with undo and reset options.
    The dialog does not block the main window. The backend ignores pickup
    and drop events once the game is over, so the move history can still
    be copied with the panel's Copy button. Undo reverts the move that ended
    the game (the backend then dismisses this window); Reset and closing the
    window start a new game.
    @param result The result of the game: "win" or "draw".
    @param reason Why the game ended, e.g. "checkmate", "stalemate" or
        "insufficient material".
    @param winner The color of the winner, or "none" for a draw.
    """
    if (verboseMode):
        pythonTools.output_text(f"Showing game result: {result} ({reason}), winner: {winner}", option="note")

    if root is None:
        raise ValueError("UI not created; call createUI() first")

    global resultDialog

    if result == "win":
        message = f"{winner.capitalize()} wins by {reason}."
    else:
        message = f"Draw by {reason}."

    if resultDialog is not None:
        resultDialog.destroy()

    resultDialog = tk.Toplevel(root)
    resultDialog.title("Game Over")
    resultDialog.resizable(False, False)
    resultDialog.transient(root)
    # The dialog is a separate Toplevel, so the root's <Control-z> binding
    # does not fire while the dialog holds focus. Bind it here too.
    resultDialog.bind("<Control-z>", lambda event: addEvent("undo_move"))
    tk.Label(resultDialog, text=message, font=("Segoe UI", 14),
             bg=BACKGROUND, fg=LABEL_FG).pack(padx=24, pady=(18, 12))
    buttonRow = tk.Frame(resultDialog)
    buttonRow.pack(pady=(0, 18))
    tk.Button(buttonRow, text="Undo",
              command=lambda: addEvent("undo_move")).pack(side=tk.LEFT, padx=8)
    tk.Button(buttonRow, text="Reset", command=resetBoard).pack(side=tk.LEFT, padx=8)
    resultDialog.protocol("WM_DELETE_WINDOW", resetBoard)
    updateUI()

def showPiecePromoBox(pieces, color):
    """
    This will display the piece promotion box.
    @param pieces The promotion options for the piece. The expected format of this is 
           a comma-delimiter string (e.g., "queen,rook,bishop,knight").
    @param color This is the color of the piece being promoted.
    """
    if (verboseMode):
        pythonTools.output_text("Displaying piece promotion box.", option="note")

    if root is None:
        raise ValueError("UI not created; call createUI() first")

    global piecePromoBox

    if piecePromoBox is not None:
        piecePromoBox.destroy()

    piecePromoBox = tk.Toplevel(root)
    piecePromoBox.title("Promote the piece!")
    piecePromoBox.resizable(False, False)
    piecePromoBox.transient(root)

    pieceFrame = tk.Frame(piecePromoBox)
    pieceFrame.pack(padx=10, pady=10)

    for piece in pieces.split(","):
        tk.Button(
            pieceFrame,
            text=glyphs[piece],
            font=("Segoe UI Symbol", 24),
            fg=color,
            activeforeground=color,
            command=lambda p=piece: sendPiecePromoChoice(p)
        ).pack(side=tk.LEFT, padx=4)

    piecePromoBox.wait_visibility(piecePromoBox)
    piecePromoBox.grab_set()

    updateUI()

# ----- options panel -----

def setTurn(color):
    """
    Shows whose turn it is on the options panel turn indicator.
    @param color "white" or "black".
    """
    if optionsPanel is None:
        raise ValueError("UI not created; call createUI() first")
    optionsPanel.setTurn(color)

def addMoveToHistory(side, move):
    """
    Appends a move to the given player's move history box on the options
    panel.
    @param side "white" or "black", the player who made the move.
    @param move The move text to display, e.g., "e2e4".
    """
    if optionsPanel is None:
        raise ValueError("UI not created; call createUI() first")
    optionsPanel.addMove(side, move)

def clearMoveHistory():
    """
    Empties both move history boxes on the options panel. The backend calls
    this when a new game starts so the boxes only ever hold the current
    game's moves.
    """
    if optionsPanel is None:
        raise ValueError("UI not created; call createUI() first")
    optionsPanel.clearMoves()

def markMoveInHistory(side, marker):
    """
    Appends a marker to the last move recorded for the given player on the
    options panel, e.g., "#" on the move which delivered checkmate.
    @param side "white" or "black", the player who made the last move.
    @param marker The text to append to that move.
    """
    if optionsPanel is None:
        raise ValueError("UI not created; call createUI() first")
    optionsPanel.markLastMove(side, marker)

def removeMoveFromHistory(side):
    """
    Removes the most recent move from the given player's move history box on the
    options panel. The backend calls this for each move an undo reverts, so the
    boxes stay in step with the game.
    @param side "white" or "black", the player who made the last move.
    """
    if optionsPanel is None:
        raise ValueError("UI not created; call createUI() first")
    optionsPanel.removeLastMove(side)

def dismissGameResult():
    """
    Closes the game result window without resetting the board. The backend
    calls this when an undo reverts the move that ended the game, so play
    continues from the restored position.
    """
    global resultDialog
    if resultDialog is not None:
        resultDialog.destroy()
        resultDialog = None
    updateUI()

def showOptionsPanel():
    """
    Opens the options panel beside the board. The backend calls this after
    createUI() when the configuration says the panel starts open. The panel
    starts closed, so nothing is called when it starts closed. The collapse
    bar still closes it afterwards.
    """
    if optionsPanel is None:
        raise ValueError("UI not created; call createUI() first")
    optionsPanel.show()

# ----- event queue -----

def getNextEvent():
    """
    Gets the next event generated by the UI.
    Events are removed from the queue when retrieved. An empty string is
    returned when there are no pending events.
    @return The next UI event, or an empty string when the queue is empty.
    """
    if not uiEvents:
        return ""
    return uiEvents.pop(0)

def getAllEvents():
    """
    Gets all events currently generated by the UI.
    Events are removed from the queue when retrieved. An empty list is
    returned when there are no pending events.
    The tkinter event loop is pumped on each call so that mouse-driven
    events keep flowing without a separate mainloop on the python side.
    @return A list containing all pending UI events.
    """
    events = uiEvents.copy()
    uiEvents.clear()

    # This can be added if desired for debugging, but is generally extremely 
    # noisy, since this method is called frequently.
    #if verboseMode:
    #    pythonTools.output_text(f"UI events retrieved: {events}", option="program")

    return events

# ----- configuration -----

def setVerbose(val):
    """
    Sets whether verbose output is enabled.
    @param val True to enable verbose output, false to disable it.
    """
    global verboseMode
    verboseMode = val
    if verboseMode:
        pythonTools.output_text("Verbose mode enabled for checkUI (python module).", option="program")


