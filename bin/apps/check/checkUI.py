#!/usr/bin/env python3
"""
@file    checkUI.py
@author  Antonius Torode
@date    10/15/2026

Python UI for the Custom House-made Engine for Chess Knowledge (CHECK)
board.
Used by the C++ backend through PythonModule.

The UI renders an N x M board of square cells with labeled borders and
supports
dragging pieces between squares. All game logic lives in the C++ backend:
the UI never decides whether a move is legal. When a piece is dropped the UI
snaps it back to its origin square and queues a drop_piece event; the backend then
calls movePiece() to make the move official.

Right clicking and dragging across the board draws an annotation arrow between
the two squares, and drawing that same arrow again removes it. A right click
which never leaves its own square toggles a persistent highlight on that
square. The left button draws no annotations: picking a piece up instead drops
the annotations which come from that square, its arrows and its highlight.
Arrows and square highlights are a local UI note: they are never queued as
events and the backend is never told about them. They are cleared for the
picked square on pickup, and everywhere whenever the position changes
(movePiece, setPiece, removePiece, setBoardState).

A thin collapse bar sits against the board's right edge. Clicking it opens
or closes the options panel (see optionsUI.py). The panel opens to the
right of the board and widens the window. Panel events join this module's
event queue like every other UI event.

A menu bar sits across the top of the window with various game actions.
The menu contents and the events they add are defined in createUI().

The Game menu can also rotate the board 180 degrees in place. Rotation only
changes which side of the board is viewed from; the position itself, and every
coordinate the backend sees, is left identical. It is a local UI action, so no
event is queued and the backend is never told about it.

Event formats (the C++ side parses these):
   Events (semicolon-separated values, squares are 0-indexed col row):
    "pickup_piece;<col>;<row>"
    "drop_piece;<fromCol>;<fromRow>;<toCol>;<toRow>"
    "reset_board"
    "save_board;<file>"
    "load_board;<file>"
    "edit_mode"
    "undo_move"
    "piece_promo_choice;<piece>"
    "stop"
   Board state (one string per occupied cell, comma-separated):
    "<col>,<row>,<type>,<color>"
   Position methods accept and return lists of state strings. An empty list
   is an empty board.

The polling listener calls getAllEvents() repeatedly. getAllEvents() pumps
the tkinter event loop before returning, so the UI stays responsive as long
as the backend keeps polling. updateUI() can also be called explicitly.

Square coordinates use a cartesian layout with the origin at the
bottom-left
square. Columns (x) increase left to right and rows (y) increase bottom to
top, so (0, 0) is the bottom-left square. This applies to event strings,
board state strings, and every public method taking a col/row pair.
"""
